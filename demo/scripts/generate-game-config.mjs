import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { parseCsv, parseParameterValue, sha256, validateParameterRows } from './parameter-table.mjs';

const root = resolve(import.meta.dirname, '..', '..');
const csvPath = resolve(root, 'docs/洞天数值参数表.csv');
const outputPath = resolve(import.meta.dirname, '..', 'src/game/frozen-parameters.ts');
const manifestPath = resolve(import.meta.dirname, '..', 'src/game/parameter-manifest.ts');

const source = await readFile(csvPath, 'utf8');
const rows = parseCsv(source);
validateParameterRows(rows, { requireFrozen: true });
const parameters = Object.fromEntries(rows.map((row) => [row.parameter_id, {
  value: parseParameterValue(row.value, row.parameter_id),
  unit: row.unit, valueType: row.value_type, status: row.status, source: row.source,
}]));
const hash = sha256(source);
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `// Generated by scripts/generate-game-config.mjs. Do not edit manually.\nexport const FROZEN_PARAMETER_SHA256 = '${hash}';\nexport const FROZEN_PARAMETERS = ${JSON.stringify(parameters, null, 2)} as const;\n`);
await writeFile(manifestPath, `// Generated by scripts/generate-game-config.mjs. Do not edit manually.\nexport const PARAMETER_MANIFEST = { version: '1.0.0-frozen', sha256: '${hash}', rows: ${rows.length}, source: 'docs/洞天数值参数表.csv' } as const;\n`);
console.log(`generated rows=${rows.length} sha256=${hash}`);
